"""
Unit Tests for F3 Detection Engine Core
Corresponds to SRS REQ-F3-10 and Issue #13 (UT_F3_05, UT_F3_06, ST_F3_09).
Verifies rule registration, pipeline dispatch, observer callbacks,
reset lifecycle, and exception isolation (SEC-02).
"""

from typing import List
import unittest
from src.detection.models import NormalizedRecord, Alert, ThreatType, Severity
from src.detection.rules.base import BaseDetector
from src.detection.engine import DetectionEngine


class DummyAlertDetector(BaseDetector):
    """Test detector that emits a fixed alert whenever a packet is processed."""

    def __init__(self, name: str = "dummy_detector", enabled: bool = True):
        super().__init__(name=name, enabled=enabled)
        self.processed_count = 0

    def process_record(self, record: NormalizedRecord) -> List[Alert]:
        self.processed_count += 1
        return [
            Alert(
                threat_type=ThreatType.ARP_SPOOFING,
                severity=Severity.LOW,
                title="Dummy Alert",
                description="Test alert generated by dummy detector",
                source_interface=record.interface,
                evidence={"count": self.processed_count},
                mitigation="No action needed",
                timestamp=record.timestamp,
            )
        ]

    def reset(self) -> None:
        self.processed_count = 0


class PassThroughDetector(BaseDetector):
    """Test detector that inspects traffic but raises no alerts."""

    def __init__(self, name: str = "passthrough_detector", enabled: bool = True):
        super().__init__(name=name, enabled=enabled)
        self.seen_records = []

    def process_record(self, record: NormalizedRecord) -> List[Alert]:
        self.seen_records.append(record)
        return []

    def reset(self) -> None:
        self.seen_records.clear()


class ExplodingDetector(BaseDetector):
    """Faulty detector that raises an unhandled exception to test SEC-02 resilience."""

    def __init__(self, name: str = "exploding_detector", enabled: bool = True):
        super().__init__(name=name, enabled=enabled)

    def process_record(self, record: NormalizedRecord) -> List[Alert]:
        raise RuntimeError("Simulated detector hardware/logic failure!")

    def reset(self) -> None:
        pass


class TestDetectionEngine(unittest.TestCase):
    """Test suite for DetectionEngine coordinator."""

    def setUp(self):
        """Create fresh engine before each test."""
        self.engine = DetectionEngine()
        self.sample_record = NormalizedRecord(
            timestamp=1728087600.0,
            interface="eth0",
            link_type="ETHERNET",
            src_mac="00:11:22:33:44:55",
            src_ip="192.168.1.10",
            protocol="TCP",
        )

    def test_register_rule_validates_type(self):
        """Verify TypeError raised if registering object not subclassing BaseDetector."""
        with self.assertRaises(TypeError):
            self.engine.register_rule("not_a_rule")  # type: ignore

        with self.assertRaises(TypeError):
            self.engine.register_rule(object())  # type: ignore

    def test_register_and_get_registered_rules(self):
        """Verify registered rules appear in get_registered_rules list."""
        dummy = DummyAlertDetector(name="rule_one")
        passthrough = PassThroughDetector(name="rule_two")

        self.engine.register_rule(dummy)
        self.engine.register_rule(passthrough)

        registered = self.engine.get_registered_rules()
        self.assertEqual(len(registered), 2)
        self.assertIn("rule_one", registered)
        self.assertIn("rule_two", registered)

    def test_disabled_rules_are_bypassed(self):
        """Verify disabled rules do not execute and are omitted from active list."""
        disabled_dummy = DummyAlertDetector(name="disabled_rule", enabled=False)
        self.engine.register_rule(disabled_dummy)

        # Should not be listed in active rules
        self.assertNotIn("disabled_rule", self.engine.get_registered_rules())

        # Should not process records or generate alerts
        alerts = self.engine.process_record(self.sample_record)
        self.assertEqual(len(alerts), 0)
        self.assertEqual(disabled_dummy.processed_count, 0)

    def test_rule_replacement_on_duplicate_name(self):
        """Verify registering a rule with an existing name replaces previous instance."""
        rule_v1 = DummyAlertDetector(name="unique_rule")
        rule_v2 = PassThroughDetector(name="unique_rule")

        self.engine.register_rule(rule_v1)
        self.engine.register_rule(rule_v2)

        self.assertEqual(len(self.engine._rules), 1)
        self.assertIs(self.engine.get_rule("unique_rule"), rule_v2)

    def test_get_and_unregister_rule(self):
        """Verify retrieving and unregistering rules by name."""
        dummy = DummyAlertDetector(name="temp_rule")
        self.engine.register_rule(dummy)

        self.assertIs(self.engine.get_rule("temp_rule"), dummy)
        self.assertIsNone(self.engine.get_rule("non_existent"))

        unregistered = self.engine.unregister_rule("temp_rule")
        self.assertTrue(unregistered)
        self.assertIsNone(self.engine.get_rule("temp_rule"))
        self.assertFalse(self.engine.unregister_rule("temp_rule"))

    def test_process_record_dispatches_and_aggregates(self):
        """Verify alerts from multiple rules are aggregated properly."""
        rule1 = DummyAlertDetector(name="detector_1")
        rule2 = DummyAlertDetector(name="detector_2")

        self.engine.register_rule(rule1)
        self.engine.register_rule(rule2)

        alerts = self.engine.process_record(self.sample_record)
        self.assertEqual(len(alerts), 2)
        self.assertEqual(len(self.engine.alerts_generated), 2)

    def test_alert_callback_invoked(self):
        """Verify alert callback is executed synchronously for each generated alert."""
        callback_alerts = []

        def alert_handler(alert: Alert):
            callback_alerts.append(alert)

        engine = DetectionEngine(alert_callback=alert_handler)
        engine.register_rule(DummyAlertDetector())

        engine.process_record(self.sample_record)
        self.assertEqual(len(callback_alerts), 1)
        self.assertEqual(callback_alerts[0].title, "Dummy Alert")

    def test_exception_isolation_protects_pipeline(self):
        """SEC-02: A crashing detector must NOT bring down the engine or stop other rules."""
        exploding_rule = ExplodingDetector(name="broken_rule")
        healthy_rule = DummyAlertDetector(name="healthy_rule")

        self.engine.register_rule(exploding_rule)
        self.engine.register_rule(healthy_rule)

        # Must not raise an exception
        alerts = self.engine.process_record(self.sample_record)

        # Healthy rule must have still executed and produced its alert
        self.assertEqual(len(alerts), 1)
        self.assertEqual(alerts[0].title, "Dummy Alert")
        self.assertEqual(healthy_rule.processed_count, 1)

    def test_callback_exception_isolation(self):
        """SEC-02: A crashing user callback must NOT crash the engine or discard the alert."""
        def faulty_callback(alert: Alert):
            raise ValueError("UI WebSocket dropped abruptly!")

        engine = DetectionEngine(alert_callback=faulty_callback)
        engine.register_rule(DummyAlertDetector())

        # Must not crash
        alerts = engine.process_record(self.sample_record)
        self.assertEqual(len(alerts), 1)
        self.assertEqual(len(engine.alerts_generated), 1)

    def test_process_records_batch(self):
        """Verify batch processing streams records and combines alerts."""
        engine = DetectionEngine()
        engine.register_rule(DummyAlertDetector())

        records = [
            NormalizedRecord(timestamp=100.0 + i, interface="eth0", link_type="ETHERNET")
            for i in range(3)
        ]
        batch_alerts = engine.process_records(records)
        self.assertEqual(len(batch_alerts), 3)
        self.assertEqual(len(engine.alerts_generated), 3)

    def test_reset_clears_alerts_and_rule_state(self):
        """Verify reset clears alerts_generated and calls reset on all detectors."""
        dummy = DummyAlertDetector()
        self.engine.register_rule(dummy)

        self.engine.process_record(self.sample_record)
        self.assertEqual(len(self.engine.alerts_generated), 1)
        self.assertEqual(dummy.processed_count, 1)

        self.engine.reset()
        self.assertEqual(len(self.engine.alerts_generated), 0)
        self.assertEqual(dummy.processed_count, 0)

    def test_none_record_handled_safely(self):
        """SEC-02: Defensive handling when record is None."""
        alerts = self.engine.process_record(None)
        self.assertEqual(alerts, [])


if __name__ == "__main__":
    unittest.main()
